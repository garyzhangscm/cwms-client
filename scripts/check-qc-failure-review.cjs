const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('src/app/routes/qc/failure-review/qc-failure-review.ts', 'utf8');
const context = {exports:{}};
vm.runInNewContext(ts.transpile(source, {module:ts.ModuleKind.CommonJS, target:ts.ScriptTarget.ES2022}),context);
const {aggregateQcResults, failingChecks, recomputeRequest, validFailureNotes} = context.exports;
assert.equal(aggregateQcResults([]),'PENDING');
assert.equal(aggregateQcResults(['PASS','PENDING']),'PENDING');
assert.equal(aggregateQcResults(['PASS','NOT_APPLY']),'PASS');
assert.equal(aggregateQcResults(['FAIL','PENDING']),'FAIL');
assert.equal(aggregateQcResults(['UNKNOWN']),'PENDING');
const fail={qcInspectionResult:'FAIL', exceptionNotes:'  damaged outer wrap  '};
const group={qcInspectionRequestItemOptions:[fail,{qcInspectionResult:'PASS'}]};
const record={qcInspectionRequestItems:[group]};
recomputeRequest(record);assert.equal(record.qcInspectionResult,'FAIL');
assert.equal(failingChecks([record]).length,1);assert.equal(validFailureNotes([fail]),true);
for(const notes of ['', '   ', 'x'.repeat(2001)]) assert.equal(validFailureNotes([{exceptionNotes:notes}]),false);
assert.equal(validFailureNotes([{exceptionNotes:'x'.repeat(2000)}]),true);
console.log('PASS: true failures vs pending, excluded checks, mandatory notes, limits and batch aggregation');
